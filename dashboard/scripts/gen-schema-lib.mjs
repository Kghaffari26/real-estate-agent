/**
 * Generates `src/data/schema.gen.ts` (zod schemas + inferred TS types) from the
 * agent's committed JSON Schema, `schemas/real_estate.schema.json`, so the dashboard's
 * types can't drift from the contract. `npm run check:schema` (and a unit test) fail
 * when the committed output is stale.
 *
 * Tolerance rules (the contract only grows additively, SPEC §6.3):
 * - a required field is validated as declared; if it's wrong, the enclosing item fails;
 * - a non-required field falls back to its JSON Schema `default` (or [] for arrays,
 *   otherwise undefined) when it's missing, and with a warning when it's malformed;
 * - arrays of objects and maps of objects drop malformed items with a warning;
 * - numeric series coerce non-numbers to null;
 * - validation-only keywords (pattern, minimum, maxLength, format) are not enforced.
 */

const HEADER = `// AUTO-GENERATED by scripts/gen-schema.mjs from schemas/real_estate.schema.json.
// Do not edit by hand: run \`npm run gen:schema\` after the agent's schema changes.
/* eslint-disable */
import { z } from 'zod';
import { bestUnion, optionalField, seriesNumber, tolerantArray, tolerantRecord } from './tolerant';
`;

const ROOTS = ['IndexOutput', 'MetroDetailOutput', 'EventsOutput', 'PulseOutput', 'AreasOutput', 'RegionOutput', 'RegionGeometry'];

function refName(ref) {
  const match = /^#\/\$defs\/(\w+)$/.exec(ref);
  if (!match) throw new Error(`Unsupported $ref: ${ref}`);
  return match[1];
}

function isNull(s) {
  return s.type === 'null';
}

function isNumeric(s) {
  return s.type === 'number' || s.type === 'integer';
}

function isObjectLike(s) {
  return Boolean(s.$ref) || s.type === 'object' || (s.anyOf ?? []).some((m) => m.$ref);
}

function collectRefs(s, into = new Set()) {
  if (Array.isArray(s)) s.forEach((x) => collectRefs(x, into));
  else if (s && typeof s === 'object') {
    if (typeof s.$ref === 'string') into.add(refName(s.$ref));
    Object.values(s).forEach((v) => collectRefs(v, into));
  }
  return into;
}

function literal(value) {
  return JSON.stringify(value);
}

function expr(s, where) {
  if (s.$ref) return `${refName(s.$ref)}Schema`;
  if (s.anyOf) {
    const hasNull = s.anyOf.some(isNull);
    const members = s.anyOf.filter((m) => !isNull(m));
    let inner;
    if (members.length === 0) inner = 'z.null()';
    else if (members.every(isNumeric)) inner = 'z.number()';
    else if (members.length === 1) inner = expr(members[0], where);
    else if (members.every((m) => m.$ref)) inner = `bestUnion([${members.map((m) => expr(m, where)).join(', ')}] as const)`;
    else if (members.every((m) => m.type === 'array')) {
      // Series maps: string[] (dates) or (number | null)[]; try strings first.
      const ordered = [...members].sort((a, b) => (a.items?.type === 'string' ? -1 : 0) - (b.items?.type === 'string' ? -1 : 0));
      inner = `z.union([${ordered.map((m) => expr(m, where)).join(', ')}])`;
    } else inner = `z.union([${members.map((m) => expr(m, where)).join(', ')}])`;
    return hasNull && members.length > 0 ? `${inner}.nullable()` : inner;
  }
  if (s.enum) return `z.enum([${s.enum.map(literal).join(', ')}])`;
  switch (s.type) {
    case 'string':
      return 'z.string()';
    case 'number':
    case 'integer':
      return 'z.number()';
    case 'boolean':
      return 'z.boolean()';
    case 'null':
      return 'z.null()';
    case 'array': {
      const items = s.items ?? {};
      if (items.anyOf && items.anyOf.some(isNull) && items.anyOf.filter((m) => !isNull(m)).every(isNumeric)) {
        return 'z.array(seriesNumber)';
      }
      if (isObjectLike(items)) return `tolerantArray(${expr(items, `${where}`)}, ${literal(where)})`;
      return `z.array(${expr(items, where)})`;
    }
    case 'object': {
      if (s.properties) return objectExpr(s, where);
      const ap = s.additionalProperties;
      if (ap && typeof ap === 'object') {
        if (isObjectLike(ap)) return `tolerantRecord(${expr(ap, where)}, ${literal(where)})`;
        return `z.record(z.string(), ${expr(ap, where)})`;
      }
      return 'z.record(z.string(), z.unknown())';
    }
    default:
      return 'z.unknown()';
  }
}

function fieldExpr(prop, required, where) {
  const base = expr(prop, where);
  if (required) return base;
  let fallback;
  if ('default' in prop) fallback = literal(prop.default);
  else if (prop.type === 'array') fallback = '[]';
  else if (prop.type === 'object' && !prop.properties) fallback = '{}';
  else fallback = 'undefined';
  return `optionalField(${base}, ${fallback}, ${literal(where)})`;
}

function objectExpr(s, name) {
  const required = new Set(s.required ?? []);
  const keys = Object.keys(s.properties).sort();
  const lines = keys.map((key) => {
    const field = fieldExpr(s.properties[key], required.has(key), `${name}.${key}`);
    return `  ${/^[A-Za-z_]\w*$/.test(key) ? key : literal(key)}: ${field},`;
  });
  return `z.object({\n${lines.join('\n')}\n})`;
}

/** Merge each root's `$defs`, refusing silently-different duplicates. */
function collectDefs(schema) {
  const defs = {};
  for (const root of ROOTS) {
    const rootSchema = schema.definitions?.[root];
    if (!rootSchema) throw new Error(`Schema has no definitions.${root}`);
    for (const [name, def] of Object.entries(rootSchema.$defs ?? {})) {
      if (defs[name] && JSON.stringify(defs[name]) !== JSON.stringify(def)) {
        throw new Error(`$defs.${name} differs between roots; the generator needs distinct names`);
      }
      defs[name] = def;
    }
    const body = { ...rootSchema };
    delete body.$defs;
    defs[root] = body;
  }
  return defs;
}

/** Order definitions so every schema is declared before it's referenced. */
function topoSort(defs) {
  const order = [];
  const state = new Map();
  const visit = (name) => {
    if (state.get(name) === 'done') return;
    if (state.get(name) === 'visiting') throw new Error(`Recursive $ref at ${name} isn't supported`);
    state.set(name, 'visiting');
    for (const dep of [...collectRefs(defs[name])].sort()) {
      if (!defs[dep]) throw new Error(`${name} references unknown $defs.${dep}`);
      visit(dep);
    }
    state.set(name, 'done');
    order.push(name);
  };
  Object.keys(defs).sort().forEach(visit);
  return order;
}

export function generate(schema) {
  const defs = collectDefs(schema);
  const blocks = topoSort(defs).map((name) => {
    const def = defs[name];
    const doc = def.description ? `/** ${def.description.replace(/\s+/g, ' ').trim().replace(/\*\//g, '*\\/')} */\n` : '';
    return (
      `${doc}export const ${name}Schema = ${expr(def, name)};\n` +
      `export type ${name} = z.output<typeof ${name}Schema>;`
    );
  });
  return `${HEADER}\n${blocks.join('\n\n')}\n`;
}
